    private static var activity: SpeechActivity {
        let frames = speech.filter { !$0.isNewline }.map { mark -> SpeechActivity.Frame in
            switch mark {
            case "S": .speech
            case "_": .quiet
            default: .unheard
            }
        }
        return SpeechActivity(firstFrame: firstFrame, frames: frames)
    }

    private static func cues(movedBy offset: Int64 = 0) -> [TimedCue] {
        lines.enumerated().map { index, range in
            TimedCue(
                id: TimedCue.ID(number: index),
                range: .milliseconds(range.lowerBound + offset) ..< .milliseconds(range.upperBound + offset),
                text: Redacted("")
            )
        }
    }

    private static func suggestion(movedBy offset: Int64 = 0) -> Int64? {
        PlayerFeature.suggestedDelay(speech: activity, cues: cues(movedBy: offset)).map { Int64(($0.duration / .milliseconds(1)).rounded()) }
    }

    @Test func findsTheDelayTheFilmNeeds() throws {
        let found = try #require(Self.suggestion())
        #expect((1_700 ... 2_100).contains(found))
    }

    @Test(arguments: [-4_000, 3_000] as [Int64])
    func followsTheSubtitlesWhereverTheyStart(_ offset: Int64) throws {
        let found = try #require(Self.suggestion(movedBy: offset))
        let expected = try #require(Self.suggestion()) - offset
        #expect(abs(found - expected) <= 100)
    }
